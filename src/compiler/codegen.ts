export function generateVerilog(netlist: Netlist, moduleName = 'logic_circuit'): string {
  const names = [...new Set([...netlist.inputs, ...netlist.outputs, ...netlist.wires, ...netlist.gates.map(g => g.output), ...netlist.gates.flatMap(g => g.inputs), ...netlist.aliases.flatMap(a => [a.input, a.output])])].filter(name => name !== '0' && name !== '1');
  const used = new Set<string>();
  const mapping = new Map<string, string>();
  for (const name of names) {
    const base = /^[A-Za-z_][A-Za-z0-9_$]*$/.test(name) && !VERILOG_RESERVED.has(name) ? name : `lc_${name.replace(/[^A-Za-z0-9_$]/g, '_')}`;
    let candidate = base;
    for (let suffix = 2; used.has(candidate); suffix++) candidate = `${base}_${suffix}`;
    mapping.set(name, candidate); used.add(candidate);
  }
  const nameOf = (name: string) => name === '0' || name === '1' ? `1'b${name}` : mapping.get(name)!;
  const ports = [...netlist.inputs, ...netlist.outputs];
  const internal = names.filter(name => !ports.includes(name));
  let safeModule = moduleName.replace(/[^A-Za-z0-9_$]/g, '_');
  if (!/^[A-Za-z_]/.test(safeModule) || VERILOG_RESERVED.has(safeModule)) safeModule = `lc_${safeModule}`;
  const lines = ['// Generated by Logi-Compile. Combinational, continuous assignments.', `module ${safeModule} (${ports.map(nameOf).join(', ')});`];
  if (netlist.inputs.length) lines.push(`  input wire ${netlist.inputs.map(nameOf).join(', ')};`);
  if (netlist.outputs.length) lines.push(`  output wire ${netlist.outputs.map(nameOf).join(', ')};`);
  if (internal.length) lines.push(`  wire ${internal.map(nameOf).join(', ')};`);
  for (const [original, renamed] of mapping) if (original !== renamed) lines.push(`  // Signal renamed: ${original.replace(/[\r\n]/g, ' ')} -> ${renamed}`);
  lines.push('');
  for (const gate of netlist.gates) {
    const [a, b] = gate.inputs.map(nameOf);
    let expression: string;
    switch (gate.type) {
      case 'NOT': expression = `~${a}`; break;
      case 'AND': expression = `${a} & ${b}`; break;
      case 'NAND': expression = `~(${a} & ${b})`; break;
      case 'OR': expression = `${a} | ${b}`; break;
      case 'NOR': expression = `~(${a} | ${b})`; break;
      case 'XOR': expression = `${a} ^ ${b}`; break;
      case 'XNOR': expression = `~(${a} ^ ${b})`; break;
    }
    lines.push(`  assign ${nameOf(gate.output)} = ${expression};`);
  }
  for (const alias of netlist.aliases) if (alias.output !== alias.input) lines.push(`  assign ${nameOf(alias.output)} = ${nameOf(alias.input)};`);
  lines.push('endmodule', '');
  return lines.join('\n');
}

export function truthTableCSV(table: TruthTable, includeWires = false): string {
  const columns = [...table.inputs, ...(includeWires ? table.wires : []), ...table.outputs];
  const escape = (value: string) => /[",\r\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
  return [columns.map(escape).join(','), ...table.rows.map(row => columns.map(name => row.values[name] ?? '').join(','))].join('\r\n');
}

export function generateCode(ir: IRResult): CodegenResult {
  const layout = layoutCircuit(ir.netlist);
  return { truthTable: generateTruthTable(ir.netlist), verilog: generateVerilog(ir.netlist), layout, svg: renderCircuitSVG(layout) };
}
