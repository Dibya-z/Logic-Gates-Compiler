import { evaluateNetlist } from './evaluator';
import { layoutCircuit, renderCircuitSVG } from './layout';
import { LIMITS, type CodegenResult, type IRResult, type Netlist, type TruthTable } from './types';

export function generateTruthTable(netlist: Netlist): TruthTable {
  if (netlist.inputs.length > LIMITS.inputs) throw new Error(`Truth tables support at most ${LIMITS.inputs} inputs.`);
  const { inputs, outputs, wires } = netlist;
  const rows = Array.from({ length: 2 ** inputs.length }, (_, index) => {
    const values = Object.fromEntries(inputs.map((name, bit) => [name, ((index >> (inputs.length - bit - 1)) & 1) as 0 | 1]));
    return { index, values: evaluateNetlist(netlist, values) };
  });
  const forms = outputs.map(output => {
    const minterms = rows.filter(row => row.values[output] === 1).map(row => row.index);
    const maxterms = rows.filter(row => row.values[output] === 0).map(row => row.index);
    const term = (index: number, isProduct: boolean) => {
      if (!inputs.length) return isProduct ? '1' : '0';
      const parts = inputs.map((name, bit) => {
        const high = !!((index >> (inputs.length - bit - 1)) & 1);
        return high === isProduct ? name : `NOT ${name}`;
      });
      return `(${parts.join(isProduct ? ' AND ' : ' OR ')})`;
    };
    return {
      output, minterms, maxterms,
      sop: `Σm(${minterms.join(',')})`, pos: `ΠM(${maxterms.join(',')})`,
      sopExpression: minterms.length ? (minterms.length === rows.length ? '1' : minterms.map(i => term(i, true)).join(' OR ')) : '0',
      posExpression: maxterms.length ? (maxterms.length === rows.length ? '0' : maxterms.map(i => term(i, false)).join(' AND ')) : '1',
    };
  });
  return { inputs: [...inputs], outputs: [...outputs], wires: [...wires], rows, forms };
}

